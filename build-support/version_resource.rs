//! Windows version resource shared by launcher/build.rs (HitMan-Rust.exe) and
//! hm1vk/build.rs (HitManVK\ddraw.dll). Both are stamped with the version in
//! the repository's `version.txt`, which tools\build.bat bumps on every run.
//!
//! Included into each build script with `#[path = ...] mod version_resource;`.

use std::path::{Path, PathBuf};
use std::process::Command;

pub const PRODUCT_NAME: &str = "Hitman-Rust";
pub const COPYRIGHT: &str = "MIT 2026";

pub struct VersionInfo<'a> {
    pub file_description: &'a str,
    pub original_filename: &'a str,
    pub internal_name: &'a str,
    /// true for a DLL (VFT_DLL), false for an application (VFT_APP).
    pub dll: bool,
}

/// Reads `version.txt` ("major.minor.patch"), sets `HITMAN_RUST_VERSION` for
/// the crate (`env!`), and on Windows compiles a VERSIONINFO resource with the
/// Windows SDK's rc.exe and links it into the binary.
pub fn embed(info: &VersionInfo) {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let ver_file = manifest.join("..").join("version.txt");
    println!("cargo:rerun-if-changed={}", ver_file.display());
    println!("cargo:rerun-if-env-changed=RC");

    let text = std::fs::read_to_string(&ver_file).unwrap_or_else(|e| panic!("cannot read {}: {e}", ver_file.display()));
    let ver = text.trim().to_string();
    let mut parts: Vec<u16> = ver
        .split('.')
        .map(|p| p.trim().parse::<u16>().unwrap_or_else(|_| panic!("version.txt: '{ver}' is not major.minor.patch (each 0-65535)")))
        .collect();
    if parts.is_empty() || parts.len() > 4 {
        panic!("version.txt: '{ver}' is not major.minor.patch");
    }
    parts.resize(4, 0);
    println!("cargo:rustc-env=HITMAN_RUST_VERSION={ver}");

    if std::env::var("CARGO_CFG_TARGET_ENV").as_deref() != Ok("msvc") {
        return;
    }
    if !cfg!(windows) {
        // Cross-checking from a non-Windows host: no rc.exe, skip the resource.
        println!("cargo:warning=not building on Windows: {} gets no version resource", info.original_filename);
        return;
    }

    let commas = parts.iter().map(|p| p.to_string()).collect::<Vec<_>>().join(",");
    let file_type = if info.dll { "0x2" } else { "0x1" };
    let rc = format!(
        r#"// Generated by build-support/version_resource.rs - do not edit.
1 VERSIONINFO
FILEVERSION {commas}
PRODUCTVERSION {commas}
FILEFLAGSMASK 0x3F
FILEFLAGS 0x0
FILEOS 0x40004
FILETYPE {file_type}
FILESUBTYPE 0x0
BEGIN
    BLOCK "StringFileInfo"
    BEGIN
        BLOCK "040904B0"
        BEGIN
            VALUE "FileDescription", "{desc}"
            VALUE "FileVersion", "{ver}"
            VALUE "InternalName", "{internal}"
            VALUE "LegalCopyright", "{COPYRIGHT}"
            VALUE "OriginalFilename", "{original}"
            VALUE "ProductName", "{PRODUCT_NAME}"
            VALUE "ProductVersion", "{ver}"
        END
    END
    BLOCK "VarFileInfo"
    BEGIN
        VALUE "Translation", 0x409, 1200
    END
END
"#,
        desc = info.file_description,
        internal = info.internal_name,
        original = info.original_filename,
    );

    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap());
    let rc_path = out.join("version.rc");
    let res_path = out.join("version.res");
    std::fs::write(&rc_path, rc).expect("write .rc");

    let rc_exe = find_rc().unwrap_or_else(|| {
        panic!(
            "rc.exe (Windows SDK resource compiler) not found. Install the Windows SDK with Visual Studio, \
             or set RC to the full path of rc.exe"
        )
    });
    let status = Command::new(&rc_exe)
        .args(["/nologo", "/c65001", "/fo"])
        .arg(&res_path)
        .arg(&rc_path)
        .status()
        .unwrap_or_else(|e| panic!("cannot run {}: {e}", rc_exe.display()));
    if !status.success() {
        panic!("{} failed ({status})", rc_exe.display());
    }
    // link.exe accepts compiled .res files as inputs.
    let kind = if info.dll { "cdylib" } else { "bins" };
    println!("cargo:rustc-link-arg-{kind}={}", res_path.display());
}

/// rc.exe: `RC` env var, then PATH (a VS developer prompt), then the newest
/// Windows 10/11 SDK under KitsRoot10.
fn find_rc() -> Option<PathBuf> {
    if let Some(p) = std::env::var_os("RC").map(PathBuf::from).filter(|p| p.is_file()) {
        return Some(p);
    }
    if let Some(path) = std::env::var_os("PATH") {
        if let Some(p) = std::env::split_paths(&path).map(|d| d.join("rc.exe")).find(|p| p.is_file()) {
            return Some(p);
        }
    }
    let mut roots = Vec::new();
    for key in [
        r"HKLM\SOFTWARE\Microsoft\Windows Kits\Installed Roots",
        r"HKLM\SOFTWARE\WOW6432Node\Microsoft\Windows Kits\Installed Roots",
    ] {
        if let Ok(o) = Command::new("reg").args(["query", key, "/v", "KitsRoot10"]).output() {
            let s = String::from_utf8_lossy(&o.stdout);
            if let Some(line) = s.lines().find(|l| l.contains("KitsRoot10")) {
                if let Some(i) = line.find("REG_SZ") {
                    roots.push(PathBuf::from(line[i + 6..].trim()));
                }
            }
        }
    }
    roots.push(PathBuf::from(r"C:\Program Files (x86)\Windows Kits\10"));
    roots.into_iter().find_map(|root| newest_sdk_rc(&root.join("bin")))
}

fn newest_sdk_rc(bin: &Path) -> Option<PathBuf> {
    let mut versions: Vec<(Vec<u32>, PathBuf)> = std::fs::read_dir(bin)
        .ok()?
        .flatten()
        .filter_map(|e| {
            let name = e.file_name().to_string_lossy().into_owned();
            let v: Option<Vec<u32>> = name.split('.').map(|x| x.parse().ok()).collect();
            v.filter(|v| v.len() == 4).map(|v| (v, e.path()))
        })
        .collect();
    versions.sort();
    versions.into_iter().rev().find_map(|(_, dir)| {
        ["x64", "x86"].iter().map(|a| dir.join(a).join("rc.exe")).find(|p| p.is_file())
    })
}
